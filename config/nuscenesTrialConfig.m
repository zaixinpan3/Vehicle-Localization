function trial=nuscenesTrialConfig(steeringRatio)
% nuscenesTrialConfig Explicit Zoe assumptions for a development transfer run.
% This is not a replacement for the adopted MnCAV vehicle configuration.
% The ratio must be supplied from separate sensor-only calibration scenes.
% Stiffness, inertia and the IMU location remain declared approximations;
% certificates apply to this assumed model, not an identified nuScenes car.
    arguments
        steeringRatio (1,1) double {mustBeFinite,mustBePositive}
    end
    mass=1468;wheelbase=2.588;frontLoad=871/1468;
    vehicle=struct('mass',mass,'lf',wheelbase*(1-frontLoad), ...
        'lr',wheelbase*frontLoad,'yawInertia',mass*(4.084^2+1.730^2)/12, ...
        'frontCorneringStiffness',60000,'rearCorneringStiffness',60000);
    provenance=struct('identity',"Renault Zoe development-trial model; loaded research-car parameters unknown", ...
        'massGeometry',"Renault Zoe UK brochure: 1468 kg curb mass, 871/597 kg static axle loads, 2.588 m wheelbase, 4.084/1.730 m body dimensions; variant/payload match unverified", ...
        'inertia',"Assumed homogeneous rectangular body, m*(length^2+width^2)/12; not identified", ...
        'stiffness',"Assumed complete-axle 60000 N/rad at each axle; not identified", ...
        'imu',"Assumed axes aligned with body and acceleration measured at CG; IMU lever arm is not supplied by the CAN expansion", ...
        'sources',["https://xr793.com/wp-content/uploads/2022/12/2015-Renault-Zoe-UK.pdf", ...
        "https://www.nuscenes.org/tutorials/can_bus_tutorial.html", ...
        "https://www.nuscenes.org/data-format"]);
    lateral=lateralObserverConfig();lateral.vehicle=vehicle;
    lateral.vehicleParameterProvenance=provenance;
    lateral.outputPoint=struct('forwardOffsetM',vehicle.lr, ...
        'identifier',"assumed-CG-to-nuScenes-rear-axle");
    lateral.sensorParameterProvenance=struct('scope',"Declared transfer priors, not MnCAV calibration");
    lateral.simulation.lateralAccelerationNoiseStd=.2;
    lateral.simulation.yawRateNoiseStd=.01;
    lateral.synthesis.measurementErrorScale=[.3;.02];
    lateral.synthesis.axleForceMismatchScale=.3*lateral.synthesis.linearLateralAccelerationScale* ...
        [vehicle.lr;vehicle.lf]/wheelbase;
    globalCfg=mncavFullObserverConfig();globalCfg.kind="nuscenes-overlap-development-trial";
    globalCfg.invariantObserver.operatingPoints=["lidar","weakLidar"];
    globalCfg.invariantObserver.balancedPoseMetric=true;
    globalCfg.invariantObserver=rmfield(globalCfg.invariantObserver,{'headingGainLimits','matchedGainLimits'});
    globalCfg.gnss.outputPoint=struct('bodyOffset',[0;0],'bodyCovariance',zeros(2), ...
        'headingStdRad',0,'identifier',"nuScenes-rear-axle");
    globalCfg.invariantObserver.noise=struct('lidarPositionM',.1,'lidarHeadingRad',.01, ...
        'gnssPositionM',1,'velocityMps',.3,'accelerationMps2',.3,'gyroRadps',.01,'jerkMps3',1);
    globalCfg.invariantObserver.provenance.noise="Declared transfer scales; no nuScenes reference-error tuning";
    globalCfg.invariantObserver.provenance.operatingPoints="LiDAR with wheel/lateral/IMU auxiliary outputs; no live GNSS or pose.vel";
    trial=struct('vehicle',vehicle,'provenance',provenance,'lateral',lateral, ...
        'global',globalCfg,'wheelRadiusM',.305,'steeringRatio',steeringRatio, ...
        'yawDerivativeTimeConstantS',.1,'maximumCanAgeS',.1);
end
