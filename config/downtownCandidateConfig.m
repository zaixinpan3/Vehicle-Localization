function cfg=downtownCandidateConfig(spacing)
% downtownCandidateConfig: Whole-pillar statistical candidate rules.
% The Downtown rule set balances precision with buffered calibration recall.
% Facade vetoes protect point coverage and require horizontal extent or
% sustained within-pillar height variance. Pole halo members retain their
% pooled vertical support. Offline fitting counts pillars once;
% Complete-height CDF gaps reject disconnected pole owners; conditional
% height variance distinguishes curb discontinuities from smooth slopes.
% Dense, continuous and dominant upright owners have a conservative pole alternative.
% Facade vetoes distinguish distributed clutter from coherent sparse wall support.
% Disconnected owners cannot borrow sparse facade support from near-vertical lines.
% Multiscale transverse covariance and height-distribution support veto sparse clutter.
% Low-height halo owners need coherent vertical-plane population support.
% target-point coverage and buffered frame checks protect localization support.
% Population CDF and count-weighted covariance descriptors support tuning.
    assert(abs(spacing-.3)<1e-12,'perception:DowntownRuleLattice', ...
        'Downtown candidate rules are calibrated for the 0.3 m lattice used by both products.');
    cfg=struct('spacing',spacing,'curbHaloMeters',0, ...
        'curbExtensionMeters',16,'curbExtensionHalfWidthMeters',0.3, ...
        'structuralHaloMeters',0.3,'facadeHaloMeters',3.0, ...
        'curbExtensionMinimumTotalEnergy',.07,'curbExtensionMinimumBaseEnergy',.20, ...
        'curbExtensionMinimumHeightStep',.025,'curbExtensionMinimumCenterEvidence',.90, ...
        'curbExtensionMaximumRelativeHeight',.25, ...
        'curbRoadPatch',struct('supportRadiusMeters',1.8,'minimumCrosswiseStdMeters',.6, ...
            'minimumAnchorPillars',4,'minimumGrade',.05,'maximumHeightErrorMeters',.07, ...
            'supportPercentile',80), ...
        'poleDistributionGate',struct('radiusCells',1, ...
            'minimumVerticalVarianceFraction',.90,'maximumRadialVariance',.10), ...
        'signMinimumReflectiveMeanClearance',1.0);
    rulePath=fullfile(fileparts(mfilename('fullpath')),'downtownBalancedRules.json');
    cfg.precisionFilter=struct('rules',jsondecode(fileread(rulePath)));
end
