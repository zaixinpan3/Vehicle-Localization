function cfg=semanticGeometryConfig()
% semanticGeometryConfig Geometry used by semantic overlap and map queries.
% These are spatial support and uncertainty settings in meters and radians.
% They do not define a pose optimizer or an acceptance threshold.
    cfg=struct('localMapRadius',100, ...
        'heightMode',"xy",'heightTranslation',NaN, ...
        'heightStandardDeviation',.20,'tiltStandardDeviation',deg2rad(.5));
    cfg.support=struct('angularFloor',deg2rad(1),'scatterScale',.1, ...
        'neighborhoodRadius',4,'minimumSpan',2.4,'directionResolution',0, ...
        'directionPower',4,'maximumGap',1.5);
end
