function validation=validate_results()
% validate_results Check the implemented interfaces and fresh production replay.
    setupVehicleLocalization;dest=fileparts(mfilename('fullpath'));
    tests=["positionAidedRegistrationTest","synchronousLocalizationTest", ...
        "geometricRegistrationTest","localizationSourceWindowTest", ...
        "distributionRegistrationTest","registrationInformationTest", ...
        "repeatabilityRegistrationTest","gnssOutputPointTest","fullLocalizationObserverTest"];
    results=runtests("tests/"+tests+".m");
    writetable(table(results),fullfile(dest,'tests.csv'));assert(all([results.Passed]));
    files=["config/distributionRegistrationConfig.m", ...
        "localization/registerSemanticProbabilityCloud.m","localization/localizeLidarFrame.m", ...
        "localization/selectPositionAidedRegistration.m","localization/matchLocalProbabilityCloud.m", ...
        "localization/registrationSupport.m","localization/runSynchronousLocalizationObserver.m", ...
        "scripts/runMncavFullObserverExperiment.m","scripts/prepareMississippiLocalizationClouds.m", ...
        "tests/positionAidedRegistrationTest.m","tests/synchronousLocalizationTest.m", ...
        "research/gnss_aided_matching_20260922/prepare_sources.m", ...
        "research/gnss_aided_matching_20260922/run_comparison.m", ...
        "research/gnss_aided_matching_20260922/analyze_aiding.m", ...
        "research/gnss_aided_matching_20260922/validate_results.m"];
    findings=arrayfun(@(f)numel(checkcode(f,'-id','-config=factory')),files);
    writetable(table(files.',findings.',VariableNames={'file','findings'}),fullfile(dest,'code_analysis.csv'));
    assert(all(findings==0));
    out='output/gnss_aided_matching_20260922';
    fresh=load(fullfile(out,'production_fresh','experiment.mat'),'data','runs','report');
    research=load(fullfile(out,'closed_loop.mat'),'aided');
    actual=fresh.runs{1}.estimate.matchingResults;
    savedPose=cell2mat(cellfun(@(r)r.poseXYTheta,actual,UniformOutput=false));
    assert(isequaln(savedPose,fresh.data.lidar.pose));
    assert(isequal(cellfun(@(r)r.accepted,actual),fresh.data.lidar.valid));
    assert(fresh.data.lidar.conditionedOnGnssSelection && ~fresh.data.lidar.informationCalibrated);
    difference=max(abs(fresh.runs{1}.estimate.pose-research.aided.pose),[],'all');
    assert(difference<1e-7,'Fresh production replay differs from the paired experiment.');
    audit=jsondecode(fileread(fullfile(dest,'audit.json')));
    validation=struct('testCount',numel(results),'testsPassed',nnz([results.Passed]), ...
        'factoryAnalyzerFindings',sum(findings),'analyzedFiles',numel(files), ...
        'productionRegeneratedRawScans',1170,'fullObserverSamples',numel(fresh.data.highRate.time), ...
        'productionScenarios',numel(fresh.runs),'savedMeasurementsMatchActualResults',true, ...
        'freshProductionPoseDifferenceMaximum',difference, ...
        'informationAudit',audit,'matlabVersion',version, ...
        'limitations',"See README; this is aligned offline replay, not independent-drive ground truth.");
    fid=fopen(fullfile(dest,'validation.json'),'w');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
    fprintf(fid,'%s\n',jsonencode(validation,PrettyPrint=true));
    writetable(fresh.report.metrics,fullfile(dest,'production_metrics.csv'));
    disp(validation);
end
