function validation=validate_height_experiment()
% validate_height_experiment Exercise height, planar and observer contracts.
    setupVehicleLocalization;dest=fileparts(mfilename('fullpath'));
    names=["relativeHeightAssociationTest","localizationSourceWindowTest","geometricRegistrationTest", ...
        "positionAidedRegistrationTest","robustPoseGraphTest","registrationInformationTest", ...
        "distributionRegistrationTest","repeatabilityRegistrationTest","heightProbabilityCloudTest", ...
        "synchronousLocalizationTest","fullLocalizationObserverTest","gnssOutputPointTest"];
    results=runtests("tests/"+names+".m");writetable(table(results),fullfile(dest,'tests.csv'));
    assert(all([results.Passed]));
    files=["config/distributionRegistrationConfig.m","localization/registrationSupport.m", ...
        "localization/updateLocalizationSourceWindow.m","localization/selectLocalProbabilityCloud.m", ...
        "localization/prepareRelativeHeightAssociation.m","localization/prepareSemanticRegistrationGeometry.m", ...
        "scripts/prepareMississippiLocalizationClouds.m","tests/relativeHeightAssociationTest.m", ...
        "research/height_association_20260923/run_height_experiment.m", ...
        "research/height_association_20260923/validate_height_experiment.m", ...
        "research/height_association_20260923/probe_height_associations.m", ...
        "research/height_association_20260923/probe_height_peak.m"];
    issues=cell(0,3);
    for file=files
        messages=checkcode(file,'-id','-config=factory');
        for j=1:numel(messages),issues(end+1,:)={file,messages(j).line,messages(j).message};end %#ok<AGROW>
    end
    writetable(cell2table(issues,VariableNames={'file','line','message'}),fullfile(dest,'code_analysis.csv'));
    validation=struct('passed',nnz([results.Passed]),'total',numel(results), ...
        'codeFilesChecked',numel(files),'codeAnalyzerFindings',size(issues,1), ...
        'matlabVersion',version);
    fid=fopen(fullfile(dest,'validation.json'),'w');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
    fprintf(fid,'%s\n',jsonencode(validation,PrettyPrint=true));disp(validation);
end
